import express from 'express';
import { getFeedPosts, getExplorePosts, getPost, getUserPosts, createPost, updatePost, deletePost, likePost, addComment, deleteComment, savePost, getSavedPosts, searchPosts, sharePost } from '../controllers/postController.js';
import { protect } from '../middleware/auth.js';
import { upload } from '../middleware/upload.js';
const router = express.Router();
router.get('/feed', protect, getFeedPosts);
router.get('/explore', protect, getExplorePosts);
router.get('/saved', protect, getSavedPosts);
router.get('/search', protect, searchPosts);
router.get('/user/:userId', protect, getUserPosts);
router.get('/:id', protect, getPost);
router.post('/', protect, upload.single('image'), createPost);
router.put('/:id', protect, upload.single('image'), updatePost);
router.delete('/:id', protect, deletePost);
router.post('/:id/like', protect, likePost);
router.post('/:id/comment', protect, addComment);
router.delete('/:id/comment/:commentId', protect, deleteComment);
router.post('/:id/save', protect, savePost);
router.post('/:id/share', protect, sharePost);
export default router;